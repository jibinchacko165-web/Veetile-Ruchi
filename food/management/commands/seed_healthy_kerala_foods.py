def create_authentic_card_image(food_name, session_name, is_veg, calories, protein, fiber, output_path):
    """Generates an elegant, high-resolution authentic Kerala food presentation image card if file does not exist."""
    if os.path.exists(output_path):
        return

    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    img = Image.new('RGB', (1024, 1024), color='#132A13')
    draw = ImageDraw.Draw(img)

    # Kerala Wood / Banana Leaf Theme Framing
    draw.rectangle([24, 24, 1000, 1000], outline='#31572C', width=6)
    draw.rectangle([34, 34, 990, 990], outline='#4F772D', width=2)

    # Header Ribbon
    draw.rectangle([34, 34, 990, 140], fill='#1B4332')
    draw.rectangle([34, 140, 990, 146], fill='#D8F3DC')

    # Main Center Plate representation
    center_x, center_y = 512, 540
    # Outer bronze / terracotta plate
    draw.ellipse([center_x - 340, center_y - 340, center_x + 340, center_y + 340], fill='#2D1E12', outline='#A07855', width=8)
    # Inner banana leaf liner
    draw.ellipse([center_x - 310, center_y - 310, center_x + 310, center_y + 310], fill='#2D6A4F', outline='#52B788', width=4)
    # Food center circle
    inner_color = '#52796F' if is_veg else '#7F4F24'
    draw.ellipse([center_x - 220, center_y - 220, center_x + 220, center_y + 220], fill=inner_color, outline='#D8F3DC', width=3)

    # Text rendering with default font
    try:
        font_large = ImageFont.truetype("arial.ttf", 46)
        font_med = ImageFont.truetype("arial.ttf", 32)
        font_small = ImageFont.truetype("arial.ttf", 26)
    except Exception:
        font_large = ImageFont.load_default()
        font_med = font_large
        font_small = font_large

    # Brand Title
    draw.text((60, 65), "VEETILE RUCHI • AUTHENTIC KERALA KITCHEN", fill='#D8F3DC', font=font_med)

    # Dish Name across center
    lines = []
    words = food_name.split()
    current = ""
    for w in words:
        if len(current + " " + w) <= 24:
            current += (" " if current else "") + w
        else:
            lines.append(current)
            current = w
    if current:
        lines.append(current)

    start_y = center_y - (len(lines) * 30)
    for i, line in enumerate(lines):
        draw.text((center_x, start_y + (i * 60)), line, fill='#FFFFFF', font=font_large, anchor="mm")

    # Dietary & Session Tag
    veg_label = "100% PURE VEGETARIAN" if is_veg else "TRADITIONAL NON-VEG"
    badge_color = '#2E7D32' if is_veg else '#C62828'
    draw.rounded_rectangle([center_x - 240, center_y + 160, center_x + 240, center_y + 215], radius=25, fill=badge_color)
    draw.text((center_x, center_y + 187), f"{session_name.upper()} • {veg_label}", fill='#FFFFFF', font=font_small, anchor="mm")

    # Bottom Nutrition Bar
    draw.rectangle([34, 880, 990, 990], fill='#081C15')
    nutr_text = f"🔥 {int(calories)} kcal  |  💪 Protein: {protein}g  |  🌾 Fiber: {fiber}g  |  🥗 Low Sodium"
    draw.text((center_x, 935), nutr_text, fill='#95D5B2', font=font_med, anchor="mm")

    img.save(output_path, format='JPEG', quality=90)


class Command(BaseCommand):
    help = "Seeds 20 healthy, authentic Kerala dishes per meal session (80 new dishes total) without touching existing foods."

    def handle(self, *args, **options):
        self.stdout.write(self.style.NOTICE("Checking existing database and preserving existing foods..."))

        # Step 1: Count existing items
        initial_count = FoodItem.objects.count()
        self.stdout.write(f"Existing foods count before seeding: {initial_count}")

        # Get or create categories
        veg_cat, _ = Category.objects.get_or_create(
            name='Vegetarian',
            defaults={'description': 'Authentic Kerala vegetarian preparations.'}
        )
        non_veg_cat, _ = Category.objects.get_or_create(
            name='Non-Vegetarian',
            defaults={'description': 'Traditional Kerala fish, chicken, and meat dishes.'}
        )

        # Get or create meal sessions
        sessions_map = {}
        session_times = {
            'Breakfast': ('06:30:00', '11:00:00'),
            'Lunch': ('11:00:00', '16:00:00'),
            'Snacks': ('16:00:00', '19:00:00'),
            'Dinner': ('19:00:00', '23:30:00')
        }
        for s_name, (st, et) in session_times.items():
            sess, _ = MealSession.objects.get_or_create(
                name=s_name,
                defaults={'start_time': st, 'end_time': et}
            )
            sessions_map[s_name] = sess

        # Designated chef
        chef_user = User.objects.filter(role='chef').first()
        if not chef_user:
            chef_user = User.objects.filter(is_superuser=True).first() or User.objects.first()

        added_counts = {'Breakfast': 0, 'Lunch': 0, 'Snacks': 0, 'Dinner': 0}
        skipped_counts = {'Breakfast': 0, 'Lunch': 0, 'Snacks': 0, 'Dinner': 0}

        for session_name, dishes in NEW_HEALTHY_KERALA_FOODS.items():
            session_obj = sessions_map[session_name]
            session_folder = session_name.lower()
            media_folder = os.path.join(settings.BASE_DIR, 'media', 'food_photos', 'new', session_folder)
            os.makedirs(media_folder, exist_ok=True)

            self.stdout.write(f"\nProcessing {len(dishes)} candidate dishes for session [{session_name}]...")

            for item in dishes:
                # Duplicate check: check name in session (case-insensitive & whitespace-trimmed)
                clean_name = " ".join(item['name'].strip().split())
                existing_item = FoodItem.objects.filter(name__iexact=clean_name, meal_session=session_obj).first()
                if existing_item:
                    skipped_counts[session_name] += 1
                    continue

                category_obj = veg_cat if item['category_name'] == 'Vegetarian' else non_veg_cat
                image_rel_path = f"/media/food_photos/new/{session_folder}/{item['image_file']}"
                image_abs_path = os.path.join(media_folder, item['image_file'])

                # Ensure image file exists on disk
                if not os.path.exists(image_abs_path):
                    create_authentic_card_image(
                        food_name=item['name'],
                        session_name=session_name,
                        is_veg=item['is_veg'],
                        calories=item['calories'],
                        protein=item['protein'],
                        fiber=item['fiber'],
                        output_path=image_abs_path
                    )

                food = FoodItem.objects.create(
                    chef=chef_user,
                    name=item['name'],
                    malayalam_name=item.get('malayalam_name', ''),
                    description=item.get('description', ''),
                    malayalam_description=item.get('malayalam_description', ''),
                    price=item['price'],
                    category=category_obj,
                    meal_session=session_obj,
                    stock_quantity=15,
                    is_available=True,
                    image=image_rel_path,
                    is_vegetarian=item['is_veg'],
                    is_vegan=item['is_vegan'],
                    contains_egg=item['contains_egg']
                )

                NutritionInfo.objects.create(
                    food_item=food,
                    calories=item['calories'],
                    protein=item['protein'],
                    carbohydrates=item['carbs'],
                    total_sugars=item['sugars'],
                    added_sugars=0.0,
                    total_fat=item['fat'],
                    saturated_fat=item['sat_fat'],
                    trans_fat=0.0,
                    fiber=item['fiber'],
                    cholesterol=item['cholesterol'],
                    sodium=item['sodium'],
                    ingredients=item['ingredients'],
                    allergens=item['allergens'],
                    serving_size=item['serving_size'],
                    cooking_method=item['cooking_method']
                )

                added_counts[session_name] += 1

        final_count = FoodItem.objects.count()
        total_added = sum(added_counts.values())

        self.stdout.write(self.style.SUCCESS(f"\n=================================================="))
        self.stdout.write(self.style.SUCCESS(f"HEALTHY KERALA FOODS SEEDING COMPLETE"))
        self.stdout.write(self.style.SUCCESS(f"Initial existing foods count (preserved): {initial_count}"))
        for s, c in added_counts.items():
            self.stdout.write(self.style.SUCCESS(f" - {s}: {c} new foods added (skipped: {skipped_counts[s]})"))
        self.stdout.write(self.style.SUCCESS(f"Total new foods added: {total_added}"))
        self.stdout.write(self.style.SUCCESS(f"Total foods in database now: {final_count}"))
        self.stdout.write(self.style.SUCCESS(f"=================================================="))
